const screens = {
  start: document.getElementById("start-screen"),
  quiz: document.getElementById("quiz-screen"),
  result: document.getElementById("result-screen"),
};

const questionCountNode = document.getElementById("question-count");
const progressTextNode = document.getElementById("progress-text");
const progressFillNode = document.getElementById("progress-fill");
const scoreTextNode = document.getElementById("score-text");
const questionTextNode = document.getElementById("question-text");
const answersGridNode = document.getElementById("answers-grid");
const feedbackTextNode = document.getElementById("feedback-text");
const resultTitleNode = document.getElementById("result-title");
const resultSummaryNode = document.getElementById("result-summary");

const startButton = document.getElementById("start-button");
const nextButton = document.getElementById("next-button");
const restartButton = document.getElementById("restart-button");

const optionThemeClasses = ["answer-a", "answer-b", "answer-c", "answer-d"];
const optionLetters = ["A", "B", "C", "D"];
const answerPool = [...new Set(questionBank.map((item) => item.answer))];

const state = {
  currentIndex: 0,
  score: 0,
  questions: [],
  isAnswered: false,
};

questionCountNode.textContent = String(questionBank.length);

function shuffle(items) {
  const copy = [...items];

  for (let index = copy.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [copy[index], copy[randomIndex]] = [copy[randomIndex], copy[index]];
  }

  return copy;
}

function getWrongAnswers(correctAnswer) {
  return shuffle(answerPool.filter((answer) => answer !== correctAnswer)).slice(0, 3);
}

function buildQuiz() {
  return shuffle(questionBank).map((item) => {
    const options = shuffle([
      { text: item.answer, isCorrect: true },
      ...getWrongAnswers(item.answer).map((text) => ({ text, isCorrect: false })),
    ]);

    return {
      ...item,
      options,
    };
  });
}

function showScreen(name) {
  Object.entries(screens).forEach(([screenName, node]) => {
    node.classList.toggle("active", screenName === name);
  });
}

function updateTopbar() {
  const total = state.questions.length;
  const currentNumber = state.currentIndex + 1;
  progressTextNode.textContent = `Вопрос ${currentNumber} из ${total}`;
  scoreTextNode.textContent = String(state.score);
  progressFillNode.style.width = `${(currentNumber / total) * 100}%`;
}

function renderQuestion() {
  const currentQuestion = state.questions[state.currentIndex];

  state.isAnswered = false;
  feedbackTextNode.textContent = "";
  feedbackTextNode.className = "feedback-text";
  nextButton.disabled = true;
  questionTextNode.textContent = currentQuestion.question;
  answersGridNode.innerHTML = "";

  currentQuestion.options.forEach((option, index) => {
    const button = document.createElement("button");
    const marker = document.createElement("span");
    const text = document.createElement("span");

    button.type = "button";
    button.className = `answer-button ${optionThemeClasses[index]}`;
    button.dataset.correct = String(option.isCorrect);
    button.dataset.index = String(index);

    marker.className = "answer-marker";
    marker.textContent = optionLetters[index];

    text.className = "answer-text";
    text.textContent = option.text;

    button.append(marker, text);
    button.addEventListener("click", () => handleAnswer(button, option));
    answersGridNode.append(button);
  });

  updateTopbar();
}

function handleAnswer(button, option) {
  if (state.isAnswered) {
    return;
  }

  state.isAnswered = true;

  const answerButtons = [...answersGridNode.querySelectorAll(".answer-button")];
  const correctOption = state.questions[state.currentIndex].answer;

  answerButtons.forEach((answerButton) => {
    const isCorrect = answerButton.dataset.correct === "true";
    answerButton.disabled = true;

    if (isCorrect) {
      answerButton.classList.add("is-correct");
    }
  });

  if (option.isCorrect) {
    state.score += 1;
    scoreTextNode.textContent = String(state.score);
    feedbackTextNode.textContent = "Верно! Отличный ответ.";
    feedbackTextNode.classList.add("success");
  } else {
    button.classList.add("is-wrong");
    feedbackTextNode.textContent = `Неправильно. Верный ответ: ${correctOption}`;
    feedbackTextNode.classList.add("error");
  }

  nextButton.disabled = false;
  nextButton.textContent =
    state.currentIndex === state.questions.length - 1 ? "Показать результат" : "Следующий вопрос";
}

function showResults() {
  const total = state.questions.length;
  const percent = Math.round((state.score / total) * 100);

  let title = "Неплохой старт";

  if (percent >= 85) {
    title = "Отличный результат";
  } else if (percent >= 60) {
    title = "Хороший результат";
  }

  resultTitleNode.textContent = title;
  resultSummaryNode.textContent = `Вы набрали ${state.score} из ${total} (${percent}%). Нажмите кнопку ниже, чтобы перемешать вопросы и пройти квиз заново.`;
  showScreen("result");
}

function startQuiz() {
  state.currentIndex = 0;
  state.score = 0;
  state.questions = buildQuiz();
  state.isAnswered = false;

  scoreTextNode.textContent = "0";
  showScreen("quiz");
  renderQuestion();
}

function goToNextQuestion() {
  if (!state.isAnswered) {
    return;
  }

  if (state.currentIndex === state.questions.length - 1) {
    showResults();
    return;
  }

  state.currentIndex += 1;
  renderQuestion();
}

function handleKeyboard(event) {
  if (!screens.quiz.classList.contains("active")) {
    return;
  }

  if (!state.isAnswered && ["1", "2", "3", "4"].includes(event.key)) {
    const targetIndex = Number(event.key) - 1;
    const button = answersGridNode.querySelector(`[data-index="${targetIndex}"]`);

    if (button) {
      button.click();
    }
  }

  if (state.isAnswered && event.key === "Enter") {
    goToNextQuestion();
  }
}

startButton.addEventListener("click", startQuiz);
nextButton.addEventListener("click", goToNextQuestion);
restartButton.addEventListener("click", startQuiz);
document.addEventListener("keydown", handleKeyboard);
